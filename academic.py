def normalize_value(value, min_val, max_val):
    """
    Normalize value to [0, 1] range
    Formula: normalized = (value - min) / (max - min)
    Justification: Linear scaling for fair comparison across different scales
    """
    if min_val == max_val:
        return 0.5  # Safe fallback if range is zero
    normalized = (value - min_val) / (max_val - min_val)
    return max(0, min(1, normalized))  # Clamp to [0, 1]

def normalize_skill(skill_rating):
    """Normalize student skill rating (0-5) to [0, 1] scale"""
    # Range: 0 (no knowledge) to 5 (expert)
    return normalize_value(skill_rating, 0, 5)

def normalize_hours(study_hours):
    """Normalize study hours (2-10) to [0, 1] scale"""
