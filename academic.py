    # Uncertainty
    uncertainty = calculate_performance_uncertainty(course_key, student_ratings, study_hours)
    report.append(f"\n PERFORMANCE UNCERTAINTY")
    report.append(f"   Base Prediction: {round(uncertainty['base_performance']*100, 1)}%")
    report.append(f"   Expected Range (±1σ): {round(uncertainty['range_1sigma'][0]*100, 1)}% - {round(uncertainty['range_1sigma'][1]*100, 1)}%")
    report.append(f"   Wider Range (±2σ): {round(uncertainty['range_2sigma'][0]*100, 1)}% - {round(uncertainty['range_2sigma'][1]*100, 1)}%")
    report.append(f"   Uncertainty Level: {round(uncertainty['std_deviation']*100, 1)}% (σ)")

    # Comparison with other recommendations
    if len(top_2_courses) > 1 and course_key in top_2_courses:
        report.append(f"\n COMPARISON WITH OTHER RECOMMENDATIONS")
        for other_course in top_2_courses:
            if other_course != course_key:
                other_suit = calculate_suitability_score(other_course, student_ratings)
                diff = (suitability - other_suit) * 100
                if diff > 0:
                    report.append(f"   vs {other_course}: +{round(diff, 1)}% better suitability")
                else:
                    report.append(f"   vs {other_course}: {round(diff, 1)}% lower suitability")

    report.append("\n" + "="*70 + "\n")
    return "\n".join(report)

