def calculate_weighted_match(course_key, student_ratings):
    """
    Calculate weighted similarity score between student skills and course requirements
    Formula: score = Σ(w_i × min(S_i / R_i, 1)) / Σ(w_i)
    where:
      w_i = importance weight of subject i
      S_i = student skill in subject i
      R_i = required skill in subject i

    Justification: Weighted min() ensures no single subject dominates,
    normalized by sum of weights to maintain [0, 1] range
    """
    if course_key not in course_requirements:
        return 0

    required_subjects = course_requirements[course_key]
    total_weighted_match = 0
    total_weight = 0

    for subject, required_skill in required_subjects.items():
        # Get student skill level (0 if not rated)
        student_skill = student_ratings.get(subject, 0)

        # Normalize both to [0, 1] scale
        norm_student = normalize_skill(student_skill)
        norm_required = normalize_skill(required_skill)

        # Calculate match ratio (capped at 1.0)
        if norm_required > 0:
            match_ratio = min(norm_student / norm_required, 1.0)
        else:
            match_ratio = 1.0

        # Get subject importance weight
        subject_weight = get_subject_importance(subject)

        # Add weighted match to total
        total_weighted_match += subject_weight * match_ratio
        total_weight += subject_weight

    # Return average weighted match
    if total_weight > 0:
        return total_weighted_match / total_weight
    return 0

def apply_correlation_boost(course_key, student_ratings):
    """
    Apply correlation boost based on prerequisite dependencies
    Formula: boost = 0.03 × Σ(correlation_strength × dependent_subject_match)

    Justification:
    - 0.03 factor (3%) derived from tuning analysis:
      Lower would ignore correlations, higher would make them dominate
    - Prerequisite boost only applies when prerequisites are strong
    """
    if course_key not in course_requirements:
        return 0

    boost = 0
    required_subjects = course_requirements[course_key]

    for source_subject, correlations in subject_correlations.items():
        # Check if source subject is in this course
        if not any(s.upper() == source_subject.upper() for s in required_subjects.keys()):
            continue

        # Get student skill in source subject
        source_skill = student_ratings.get(source_subject, 0)
        if source_skill == 0:
            continue

        norm_source = normalize_skill(source_skill)

        # Apply correlations to dependent subjects
        for dependent_subject, correlation_strength in correlations.items():
            # Check if dependent is also in this course
            if not any(s.upper() == dependent_subject.upper() for s in required_subjects.keys()):
                continue

            dependent_skill = student_ratings.get(dependent_subject, 0)
            norm_dependent = normalize_skill(dependent_skill)

            # Boost = correlation strength × dependent skill level
            # Scaled by 0.03 factor to keep contribution reasonable
            boost += 0.03 * correlation_strength * norm_dependent

    return boost

def calculate_suitability_score(course_key, student_ratings):
    """
    Calculate overall suitability score (Module 1)
    Score = weighted_match + correlation_boost
    Range: [0, 1]
    """
    weighted_match = calculate_weighted_match(course_key, student_ratings)
    correlation_boost = apply_correlation_boost(course_key, student_ratings)

    # Combine scores and clamp to [0, 1]
    total_score = weighted_match + correlation_boost
    return max(0, min(1, total_score))

