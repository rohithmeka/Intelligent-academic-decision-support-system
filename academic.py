def calculate_risk_prediction(course_key, student_ratings, study_hours):
    """
    Calculate academic risk prediction (Module 2)
    Formula: P = (WEIGHT_SKILL × S') + (WEIGHT_HOURS × H') + (WEIGHT_DIFFICULTY × D')
    where S', H', D' are normalized values

    Justification: Linear weighted model based on three factors:
    - Student skill (50%): Most important predictor
    - Study hours (30%): Effort multiplier
    - Course difficulty (20%): Inherent course challenge

    Risk Classification (Percentile-based, not absolute):
    - P >= 0.65: LOW RISK (top 33% of students)
    - 0.45 <= P < 0.65: MEDIUM RISK (middle 33%)
    - P < 0.45: HIGH RISK (bottom 33%)
    """
    # Get normalized values
    avg_student_skill = calculate_course_avg_skill(course_key, student_ratings)
    norm_skill = normalize_skill(avg_student_skill)

    norm_hours = normalize_hours(study_hours)

    avg_difficulty = calculate_course_avg_difficulty(course_key)
    norm_difficulty = normalize_difficulty(avg_difficulty)

    # Calculate predicted performance using linear model
    predicted_performance = (
        WEIGHT_SKILL * norm_skill +
        WEIGHT_HOURS * norm_hours +
        WEIGHT_DIFFICULTY * norm_difficulty
    )

    # Classify risk based on percentile thresholds
    if predicted_performance >= RISK_LOW_THRESHOLD:
        risk_level = " LOW RISK"
        risk_description = "High likelihood of success"
    elif predicted_performance >= RISK_MEDIUM_THRESHOLD:
        risk_level = " MEDIUM RISK"
        risk_description = "Manageable with consistent effort"
    else:
        risk_level = " HIGH RISK"
        risk_description = "Significant challenges ahead"

    return {
        "score": round(predicted_performance, 3),
        "level": risk_level,
        "description": risk_description
    }

